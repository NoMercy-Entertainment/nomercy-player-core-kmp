package tv.nomercy.player.core.ports

import android.util.Base64
import java.io.File

// Two video tracks in one file: 640x360 and 320x180.
//
// A real adaptive ladder needs a server, and a device test that reached for one
// would fail on a runner's network rather than on the code. Two tracks in one
// container exercise the same path — Media3 reports them as separate rungs and a
// selection override picks between them — without anything to serve.
//
// A literal rather than an asset because the Android KMP library plugin does not
// wire an assets directory for the device-test source set, so a file placed the
// conventional way is not packaged.
internal fun writeLadderClip(target: File): File {
    target.writeBytes(Base64.decode(LADDER_BASE64, Base64.DEFAULT))
    return target
}


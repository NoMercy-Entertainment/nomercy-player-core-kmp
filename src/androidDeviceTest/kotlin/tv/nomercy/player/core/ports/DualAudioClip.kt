import android.util.Base64
import java.io.File

// One video track and two audio tracks, English and Dutch.
//
// Two, because one cannot tell a working switch from a no-op: with a single
// track, "select the other one" and "do nothing" read identically, which is
// the shape of gate that stays green through the bug it was written for.
//
// The languages are the falsifiable part. Track ids are positional and would
// look right even if the mapper read the wrong field; eng and nld are in the
// container's metadata and can only arrive by being read out of it.
//
// A literal rather than an asset for the same reason as the ladder clip: the
// Android KMP library plugin does not wire an assets directory for the
// device-test source set, so a file placed the conventional way is not
// packaged. Built by ffmpeg from two sine tones, 32x32 black video, 8 seconds.
internal fun writeDualAudioClip(target: File): File {
    target.writeBytes(Base64.decode(DUAL_AUDIO_BASE64, Base64.DEFAULT))
    return target
}


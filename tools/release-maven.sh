#!/usr/bin/env bash
set -euo pipefail

tag="${GITHUB_REF_NAME:?run on a version tag}"
version="${tag#v}"
[ "$tag" = "v$version" ] || { echo 'expected a v-prefixed tag' >&2; exit 1; }
stage=build/release-maven

./gradlew -I tools/release-maven.init.gradle publishAllPublicationsToReleaseAssetsRepository \
  "-PVERSION_NAME=$version" --no-configuration-cache

python3 - "$stage" "$version" <<'PY'
from pathlib import Path
import sys

root, version = Path(sys.argv[1]), sys.argv[2]
# Each file, its .asc and its .sha1 only. Core's Apple targets stage more than
# the 1000-asset release limit with .md5/.sha256/.sha512; Gradle needs .sha1 alone.
def kept(p):
    stem = p.name[:-4] if p.name.endswith('.asc') else p.name[:-5] if p.name.endswith('.sha1') else p.name
    return not stem.endswith(('.asc', '.md5', '.sha1', '.sha256', '.sha512'))
files = sorted(p for p in root.rglob('*') if p.is_file() and not p.name.startswith('maven-metadata.xml')
               and kept(p))
if not files:
    raise SystemExit('no Maven files staged')
names = [p.name for p in files]
if len(names) != len(set(names)):
    raise SystemExit('release assets would have duplicate filenames')
if len(files) >= 1000:
    raise SystemExit(f'{len(files)} Maven files exceed the release asset limit')
for path in files:
    if f'-{version}' not in path.name:
        raise SystemExit(f'wrong version in {path}')
    if path.suffix not in ('.asc', '.sha1'):
        for suffix in ('.asc', '.sha1'):
            if not (path.parent / (path.name + suffix)).is_file():
                raise SystemExit(f'missing {suffix} for {path}')
Path('build/release-maven-files.txt').write_text('\n'.join(str(p) for p in files) + '\n')
print(f'{len(files)} signed Maven files staged across {len({p.parent for p in files})} artifacts')
PY

if ! gh release view "$tag" >/dev/null 2>&1; then
  gh release create "$tag" --title "$tag" --generate-notes
fi

# Existing assets may be a framework or an earlier retry. Never replace one,
# and fail if a retry generated bytes different from what was already released.
gh release view "$tag" --json assets > build/release-assets.json
python3 - <<'PY'
from pathlib import Path
import hashlib
import json

assets = {asset['name']: asset for asset in json.loads(Path('build/release-assets.json').read_text())['assets']}
staged = [Path(line) for line in Path('build/release-maven-files.txt').read_text().splitlines()]
upload = []
for path in staged:
    existing = assets.get(path.name)
    if existing is None:
        upload.append(str(path))
        continue
    digest = 'sha256:' + hashlib.sha256(path.read_bytes()).hexdigest()
    if existing['size'] != path.stat().st_size or existing.get('digest') != digest:
        raise SystemExit(f'existing release asset differs: {path.name}')
if len(assets) + len(upload) > 1000:
    raise SystemExit('release would exceed 1000 assets')
Path('build/release-upload-files.txt').write_text('\n'.join(upload) + ('\n' if upload else ''))
print(f'{len(staged)} staged; {len(upload)} new release assets')
PY
# Deliberate red run: macOS system bash 3.2 has no mapfile.
mapfile -t upload < build/release-upload-files.txt
if (( ${#upload[@]} > 0 )); then
  gh release upload "$tag" "${upload[@]}"
fi
